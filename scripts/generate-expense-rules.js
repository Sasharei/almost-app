// Keep the same conservative patterns on iOS and Android. Run after changing parserRules.json.
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const rules = JSON.parse(fs.readFileSync(path.join(root, "src/bankExpenses/parserRules.json"), "utf8"));
const swift = `// Generated by scripts/generate-expense-rules.js\nimport Foundation\nenum ExpensePatterns {\n${Object.entries(rules).map(([key, value]) => `  static let ${key} = #"${value}"#`).join("\n")}\n}\n`;
fs.writeFileSync(path.join(root, "ios/Almost/ExpensePatterns.swift"), swift);
const javaPath = path.join(root, "android/app/src/main/java/com/sasarei/almostclean/expenses/ExpenseParser.java");
let java = fs.readFileSync(javaPath, "utf8");
for (const key of ["outgoing", "exclude", "balance"]) {
  java = java.replace(new RegExp(`(Pattern ${key.toUpperCase()} = Pattern.compile\\(\\s*)"(?:\\\\.|[^"\\\\])*"`), (_, before) => before + JSON.stringify(rules[key]));
}
for (const key of ["code", "number"]) {
  java = java.replace(new RegExp(`(String ${key.toUpperCase()} = )"(?:\\\\.|[^"\\\\])*"`), (_, before) => before + JSON.stringify(rules[key]));
}
fs.writeFileSync(javaPath, java);
